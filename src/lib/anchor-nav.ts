/**
 * ============================================================================
 *  anchor-nav.ts — единая якорная навигация.
 * ----------------------------------------------------------------------------
 *  ГРАНИЦА С `scroll-to.ts`. Два модуля, и делят они работу так:
 *
 *    scroll-to.ts   — КАК доехать: геометрия (шапка, липкий остров,
 *                     cookie-полоса, режимы `fit`/`start`), доводка до
 *                     устойчивости, сторож раскладки.
 *    anchor-nav.ts  — КУДА и ПО КАКОМУ ПОВОДУ: перехват кликов, холодный заход
 *                     по `#hash`, `hashchange`, «назад/вперёд», логотип,
 *                     реестр нестандартных целей.
 *
 *  Здесь нет ни одного вычисления координат — всё уходит в `scrollToElement`.
 *
 *  ЗАЧЕМ ЭТОТ СЛОЙ ВООБЩЕ. Нативный якорь браузера считает позицию по той
 *  раскладке, которая есть В МОМЕНТ ПРЫЖКА, и больше к вопросу не
 *  возвращается. На живой странице этого мало: высота меняется после прыжка —
 *  снимается `content-visibility`, доезжают картинки и шрифты, строится
 *  ленивая сцена с пином. Нативный якорь при этом ещё и знает только про
 *  `scroll-padding-top`, то есть умеет ровно один режим — «верх секции под
 *  шапку», и уводит карточку формы под липкий остров на мобильном.
 *
 *  Разбор с замерами, из которого выросли оба модуля:
 *  docs/recipes/scroll-pitfalls.md §1, §3, §4, §9, §10.
 * ============================================================================
 */

import { cancelScrollTo, scrollToElement, type ScrollToOptions } from './scroll-to';

/**
 * Просьба всем, кто лениво меняет высоту документа, сделать это ПРЯМО СЕЙЧАС.
 *
 * В самом стартере слушателей нет и не нужно: `ScrollScene.astro` пинится
 * `position: sticky` с CSS-распоркой в `svh`, поэтому высота документа верна с
 * первого кадра. Событие существует для проектов, которые добавят пин на
 * GSAP ScrollTrigger: тот создаёт распорку лениво, уже ПОСЛЕ того как браузер
 * отработал фрагмент URL, и все якоря ниже сцены разом уезжают на её высоту.
 * Такая сцена должна поймать это событие и построиться немедленно, не дожидаясь
 * приближения к экрану (docs/recipes/scroll-pitfalls.md §4).
 *
 * Событие — не обязательство: доводка не ждёт ответа и не знает, услышал ли
 * его кто-нибудь. Оно только сокращает коррекцию до пары кадров.
 *
 * ПОДПИСЧИК ОБЯЗАН БЫТЬ ИДЕМПОТЕНТНЫМ. За один якорный клик событие приходит
 * ДВАЖДЫ: сначала из перехватчика кликов (чтобы раскладка была ближе к правде
 * ещё до прыжка самого браузера), потом из `landOn` по `hashchange`. Сцена,
 * которая на каждое событие пересоздаёт себя заново, снесёт собственный пин
 * посреди доводки.
 */
export const PREPARE_EVENT = 'anchor:prepare';

/** Класс-предохранитель `content-visibility` (правило `:root.cv-off` в
 *  global.css). Пропущенные секции стоят на ОЦЕНОЧНОЙ высоте, поэтому позиции
 *  якорей считаются по приблизительной раскладке. Первое же якорное
 *  взаимодействие снимает оптимизацию со страницы целиком: она нужна первому
 *  кадру, а к моменту клика он давно отрисован. */
const CV_CLASS = 'cv-off';

/* ==========================================================================
   Реестр целей
   ========================================================================== */

/** Куда вести и с какими настройками. `null` — цели сейчас нет. */
export interface AnchorTarget {
  el: HTMLElement;
  opts?: ScrollToOptions;
}

export type AnchorResolver = () => AnchorTarget | null;

const resolvers = new Map<string, AnchorResolver>();

/**
 * Зарегистрировать нестандартную цель для `#id`.
 *
 * По умолчанию якорь ставит ВЕРХ элемента под шапку (`block: 'start'`) — так
 * ведёт себя нативный якорь, и для секций это правильно. Но не для всего:
 * карточка формы должна попасть в экран ЦЕЛИКОМ, между шапкой и липким
 * островом, иначе на мобильном её поля уезжают под фиксированный CTA. Такие
 * случаи регистрируют свою цель с `block: 'fit'` — знание о собственной
 * раскладке остаётся в самой секции.
 *
 * Повторный вызов заменяет прежнюю цель, поэтому звать можно из
 * `astro:page-load` на каждом переходе.
 */
export function registerAnchorTarget(id: string, resolve: AnchorResolver): void {
  resolvers.set(id, resolve);
  // Список нестандартных якорей виден снаружи — им пользуется приёмочный стенд
  // (`scripts/anchor-audit.mjs`). Стенд меряет промах по контракту обычной
  // секции («верх под шапку»), а у такой цели контракт другой: `fit` ставит
  // элемент в свободное окно ЦЕЛИКОМ, и мерка не подходит. Без этой подсказки
  // автовыбор цели наткнулся бы на форму расчёта и показал ровный промах во
  // всех клетках на исправном сайте (замер 28.08.2026: −76px).
  const w = window as typeof window & { __anchorNavCustom?: string[] };
  if (!w.__anchorNavCustom) w.__anchorNavCustom = [];
  if (!w.__anchorNavCustom.includes(id)) w.__anchorNavCustom.push(id);
}

/** Идентификатор из хеша: без решётки, раскодированный. `''` — хеша нет. */
function anchorId(hash: string): string {
  const raw = hash.startsWith('#') ? hash.slice(1) : hash;
  if (!raw) return '';
  try {
    return decodeURIComponent(raw);
  } catch {
    return raw; // битый percent-encoding — пробуем как есть
  }
}

/**
 * Цель для якоря. `getElementById`, а не `querySelector('#' + id)`: id вида
 * `123` или с точкой — валидный HTML, но невалидный CSS-селектор, и
 * `querySelector` на нём бросает.
 */
function targetFor(id: string): AnchorTarget | null {
  const custom = resolvers.get(id);
  if (custom) return custom();
  const el = document.getElementById(id);
  return el ? { el, opts: { block: 'start' } } : null;
}

/**
 * Есть ли на странице куда вести. Зарегистрированный резолвер именно
 * СПРАШИВАЕМ, а не считаем наличие записи в реестре за ответ: секция может
 * быть зарегистрирована, но её карточки сейчас в разметке нет, и тогда честный
 * ответ — «вести некуда». Иначе получался съеденный клик: `onClick` отменял
 * действие браузера, `landOn` внутри упирался в `null` и возвращал `false`, а
 * вернуть клик браузеру было уже нечем — не происходило вообще ничего.
 *
 * Побочных эффектов нет: `content-visibility` — оптимизация ОТРИСОВКИ, элемент
 * при ней остаётся в дереве документа и находится как обычно.
 */
function hasTarget(id: string): boolean {
  return targetFor(id) !== null;
}

/* ==========================================================================
   Подготовка раскладки
   ========================================================================== */

/**
 * Снять `content-visibility` со страницы целиком.
 *
 * Синхронный флаш раскладки в конце — ГЛАВНОЕ в функции, а не сам класс.
 * Снятие меняет высоту всех непрорисованных секций, но применилось бы только
 * к следующему кадру, а цель считается прямо сейчас, в этой же задаче. Флаш
 * безусловный, даже если класс уже стоял: класс мог поставить инлайн-скрипт в
 * `<head>`, когда `document.body` ещё не существовал.
 */
function retireContentVisibility(): void {
  document.documentElement.classList.add(CV_CLASS);
  if (document.body) void document.documentElement.scrollHeight;
}

function prepare(): void {
  retireContentVisibility();
  document.dispatchEvent(new CustomEvent(PREPARE_EVENT));
}

/* ==========================================================================
   Публичные переходы
   ========================================================================== */

/**
 * Довести страницу до якоря. `false` — такого якоря на странице нет; тогда
 * вызывающий не должен был отменять действие браузера.
 *
 * АНИМАЦИЮ РЕШАЕТ КОНТЕКСТ, А НЕ ЦЕЛЬ.
 *
 *  • по клику — плавно. Человек видит, куда его повезли, и не теряет связь
 *    между нажатой ссылкой и новым местом. Длинный путь `scroll-to.ts`
 *    вдобавок «перематывает» (см. `rewindStart`), так что пролёта через
 *    десяток тяжёлых секций всё равно не будет;
 *  • по адресу (холодный заход, `hashchange` без клика, «назад») —
 *    мгновенно. Ползти с первого экрана к блоку, который человек запросил
 *    прямой ссылкой, — это не плавный переход, а долгая пустая пауза.
 *
 * Поэтому `animate` приходит параметром, а зарегистрированная цель на него не
 * влияет: цель отвечает за ГЕОМЕТРИЮ (`block`, резервы), контекст — за
 * СПОСОБ добраться. Смешивать эти две ответственности в одном месте — верный
 * способ получить плавное ползание при холодном заходе.
 */
export function landOn(hash: string, animate = false): boolean {
  const id = anchorId(hash);
  if (!id) return false;

  // Цель ищем ДО `prepare()`. Тот снимает content-visibility со всей страницы
  // и заставляет ленивые сцены строиться — платить за это ради
  // несуществующего якоря незачем, да и менять раскладку под браузером,
  // которому мы этот клик сейчас же вернём, нечестно.
  const target = targetFor(id);
  if (!target) return false;

  prepare();
  scrollToElement(target.el, { block: 'start', ...target.opts, animate });
  return true;
}

/**
 * Довести страницу до начала.
 *
 * Через тот же `scrollToElement`, а не одиночным `scrollTo(0, 0)`: высота
 * документа может измениться прямо во время перехода, и одиночный вызов
 * остался бы позади, а так переход получает доводку и сторож раскладки
 * даром. Целью выступает `body`: его верх — это ноль документа, а вычесть
 * шапку и зазор `computeTargetY` всё равно не даст — результат зажат снизу
 * нулём.
 */
export function landOnTop(animate = false): void {
  prepare();
  scrollToElement(document.body, { animate, block: 'start', extraTopReserve: 0 });
}

/* ==========================================================================
   Точки входа
   ========================================================================== */

/** Модификаторы и средняя кнопка — намерение открыть в новой вкладке. Такой
 *  клик перехватывать нельзя. */
function isPlainClick(ev: MouseEvent): boolean {
  return (
    !ev.defaultPrevented &&
    ev.button === 0 &&
    !ev.metaKey &&
    !ev.ctrlKey &&
    !ev.shiftKey &&
    !ev.altKey
  );
}

/**
 * Перехват кликов по ссылкам. Обрабатываем два случая, оба — «мы уже на этой
 * странице»:
 *
 *  1. ссылка с якорем → ведём к якорю сами;
 *  2. ссылка БЕЗ якоря на текущий же адрес → ведём к началу страницы.
 *
 * Второй случай — это логотип в шапке. Роутер Astro навигацию на тот же URL
 * пропускает, поэтому без перехвата логотип оказывается мёртвой ссылкой: люди
 * жмут его, чтобы вернуться наверх, и не происходит ничего. Правило намеренно
 * общее, а не «если это логотип»: любая ссылка на страницу, где мы уже стоим,
 * должна вести к её началу.
 *
 * Ссылки на ДРУГИЕ страницы (в том числе `/#section` из каталога) не трогаем
 * вовсе — их ведёт роутер Astro, а якорь доберём на `astro:page-load`.
 *
 * Слушатель в фазе перехвата и на `document`, который переживает SPA-свопы, —
 * один на всю жизнь вкладки (docs/recipes/scroll-pitfalls.md §6).
 */
function onClick(ev: MouseEvent): void {
  if (!isPlainClick(ev)) return;

  const node = ev.target instanceof Element ? ev.target : null;
  const a = node?.closest('a[href]') as HTMLAnchorElement | null;
  if (!a || a.target === '_blank' || a.hasAttribute('download')) return;

  let url: URL;
  try {
    url = new URL(a.href, location.href);
  } catch {
    return;
  }
  // Сравниваем адрес ЦЕЛИКОМ до решётки, вместе с query-строкой. Только по
  // `pathname` было бы мало: `/catalog/?page=2` со страницы `?page=1` — это
  // настоящий переход, и перехватить его значило бы увезти человека наверх той
  // же страницы вместо второй.
  if (url.origin !== location.origin) return;
  if (url.pathname !== location.pathname || url.search !== location.search) return;

  if (url.hash.length > 1) {
    if (!hasTarget(anchorId(url.hash))) return; // якоря тут нет — решает браузер

    if (url.hash === location.hash) {
      // Повторный клик по тому же якорю: адрес не меняется, значит не будет ни
      // записи в истории, ни `hashchange`. Ведём сами — человек мог отлистать
      // и жмёт пункт меню именно чтобы вернуться.
      // `preventDefault` — только если реально повели. Порядок важен: клик
      // отменяется в любой момент до возврата из обработчика, а вот отдать его
      // обратно браузеру, уже отменив, невозможно.
      if (landOn(url.hash, true)) ev.preventDefault();
      return;
    }

    // ДОРОГА ЦЕЛИКОМ НАША. Клик отменяем и запись в историю кладём сами.
    //
    // Сначала было наоборот: клик не отменялся, запись заводил браузер, а мы
    // доводили после. Обоснование — «свой `pushState` сломает бухгалтерию
    // роутера Astro» — оказалось неверным: при нативном переходе по фрагменту
    // браузер кладёт запись с ПУСТЫМ состоянием, ровно как `pushState(null)`
    // ниже. Роутеру от этого ни лучше, ни хуже.
    //
    // А расплата была тяжёлой. Замер 28.08.2026 (клик по «Шоуруму» с верха
    // страницы): в 5666мс браузер мгновенно швырял страницу с 0 на 9159,
    // в 5673мс наша «перемотка» откидывала её назад на 7326, и только потом
    // начиналась плавная часть до 12231. Два жёстких телепорта перед каждой
    // анимацией — это и читалось как «дёргано». У одной прокрутки было два
    // хозяина, и первым всегда успевал браузер.
    //
    // `pushState` не поднимает `hashchange`, поэтому ведём отсюда же, сразу и
    // плавно. Прерывание на лету получается бесплатно: следующий клик отменит
    // текущий полёт и нацелится от ТЕКУЩЕЙ точки, без прыжка.
    ev.preventDefault();
    if (!landOn(url.hash, true)) return;
    history.pushState(null, '', url.hash);
    return;
  }

  // Ссылка на текущую страницу без якоря — наверх.
  ev.preventDefault();
  if (location.hash) {
    // Хеш убираем, иначе следующая перезагрузка снова уедет к якорю.
    // `replaceState`, а не push: новая запись здесь не нужна, а чужие поля
    // состояния роутера остаются нетронутыми.
    history.replaceState(history.state, '', url.pathname + url.search);
  }
  landOnTop(true);
}

/**
 * Последний якорь, до которого мы довели страницу САМИ (без клика), и было ли
 * это приземление уже отработано.
 *
 * Модуль зовётся дважды за загрузку: при исполнении (сразу после разбора DOM)
 * и на `astro:page-load`. Второй заход не должен возвращать человека к якорю,
 * если он к этому моменту отлистал сам.
 */
let autoHash = '';
let autoLanded = false;


/**
 * Человек тронул прокрутку — считаем, что дальше она его.
 *
 * Слушать только `wheel`/`touchstart` мало: стрелки и PageDown такого события
 * не дают вовсе, а перетаскивание полосы прокрутки не даёт ни одного события
 * ввода в принципе (docs/recipes/scroll-pitfalls.md §10). Поэтому главный
 * сигнал — само событие `scroll`, случившееся НЕ во время нашей прокрутки:
 * флаг `__scrollToActive` поднимает `scroll-to.ts` ровно на время своей
 * доводки, и всё, что приходит помимо неё, — чужое движение.
 */
function markUserTookOver(): void {
  autoLanded = true;
}

function onAnyScroll(): void {
  if (window.__scrollToActive) return; // это наша же доводка
  autoLanded = true;
}

function landFromLocation(): void {
  const hash = location.hash;
  if (hash.length <= 1) return;
  if (autoHash === hash && autoLanded) return; // уже приводили, и человек с тех пор здесь хозяин
  // Приземление ПО АДРЕСУ — всегда мгновенное: холодный заход, ввод адреса,
  // ссылка извне, «назад». Ползти с первого экрана к блоку, который человек
  // запросил прямой ссылкой, — не переход, а пустая пауза. Клики сюда больше
  // не попадают: их ведёт `onClick` напрямую и плавно.
  if (landOn(hash, false)) {
    autoHash = hash;
    autoLanded = false;
  }
}

/**
 * Включает систему. Идемпотентна: слушатели вешаются один раз на вкладку
 * (`document`/`window` переживают SPA-свопы), поэтому её можно звать и при
 * исполнении модуля, и на каждом `astro:page-load`.
 *
 * Звать её ТОЛЬКО на `astro:page-load` — типичная ошибка: это событие
 * приходит на `window.load`, а на холодной загрузке с медленной сетью между
 * разбором DOM и `load` проходят секунды, в течение которых браузер давно
 * отработал фрагмент и уехал не туда. Поэтому первый заход делается прямо при
 * исполнении модуля (`<script>` в Astro — это `type=module`, то есть сразу
 * после разбора DOM), а `astro:page-load` нужен уже только SPA-переходам.
 * Подробности — docs/recipes/scroll-pitfalls.md §4.
 */
export function initAnchorNav(): void {
  const w = window as typeof window & { __anchorNavInit?: boolean };

  if (!w.__anchorNavInit) {
    w.__anchorNavInit = true;

    ['wheel', 'touchstart'].forEach((type) => {
      window.addEventListener(type, markUserTookOver, { passive: true });
    });
    window.addEventListener('scroll', onAnyScroll, { passive: true });

    document.addEventListener('click', onClick, true);

    // Хеш сменился (клик по ссылке, ввод адреса, ссылка извне) — ведём.
    // Защита от повторного приземления здесь не нужна и вредна: раз хеш
    // изменился, это новое осознанное намерение.
    window.addEventListener('hashchange', () => {
      autoHash = '';
      landFromLocation();
    });

    // «Назад/вперёд» на записи с якорем — тоже осознанное действие, ведём
    // всегда. Без хеша здесь работает `scroll-restore.ts`, он восстанавливает
    // позицию по ориентиру.
    window.addEventListener('popstate', () => {
      if (location.hash.length <= 1) return;
      autoHash = '';
      landFromLocation();
    });

    // Уход со страницы во время доводки: цель вот-вот отвяжется от документа,
    // и сторож раскладки будет сторожить чужую.
    document.addEventListener('astro:before-swap', cancelScrollTo);
    window.addEventListener('pagehide', cancelScrollTo);
  }

  landFromLocation();
}
