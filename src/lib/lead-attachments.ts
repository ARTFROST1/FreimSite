/**
 * ============================================================================
 *  lead-attachments.ts — лимиты вложений и чистая логика отбора файлов.
 * ----------------------------------------------------------------------------
 *  ЕДИНАЯ ТОЧКА ПРАВДЫ для лимитов. Модуль намеренно не знает ни про DOM, ни
 *  про `node:fs`: его импортируют ОБА берега — браузерный
 *  `components/ui/LeadAttachments.astro` (фильтрует набор до отправки и
 *  объясняет посетителю отказ) и серверный `lib/lead-server/leads.ts`
 *  (`saveAttachments` режет то же самое ещё раз, потому что клиент можно
 *  обойти). Пока константы жили в двух местах, они расходились молча: форма
 *  принимала шестой файл, сервер его выбрасывал, а посетитель был уверен, что
 *  прислал всё.
 *
 *  ТИП ФАЙЛОВ НЕ ОГРАНИЧИВАЕМ. Белый список расширений на боевом сайте терял
 *  живые заявки: `.heic` с айфона, `.docx` со сметой, `.zip` с проектом. Сайт
 *  файл не открывает и не отдаёт по HTTP — только сохраняет и пересылает
 *  менеджеру, поэтому фильтровать по типу нечего. Безопасность обеспечивает
 *  сервер: имя файла на диске он собирает сам (`safeExt` в leads.ts).
 *
 *  Тексты отказов собираются ИЗ констант (`MAX_FILES`, `MAX_FILE_SIZE_LABEL`),
 *  чтобы поднятый лимит не оставил в интерфейсе прошлую цифру.
 * ============================================================================
 */

/** Сколько файлов принимаем с одной заявки. */
export const MAX_FILES = 5;

/** Потолок размера одного файла: 5 МБ (мессенджеры ботов дальше не тянут). */
export const MAX_FILE_SIZE = 5 * 1024 * 1024;

/**
 * Тот же потолок словами — для подсказок и причин отказа. Округление ТОЛЬКО
 * вниз (и до десятых): подпись «5 МБ» при лимите 4.8 МБ — это обещание, которое
 * форма не сдержит, посетитель получит отказ на файл ровно того размера,
 * который ему разрешили. Целое число печатается без хвоста: `5 МБ`, не `5.0`.
 */
export const MAX_FILE_SIZE_LABEL = `${Math.floor((MAX_FILE_SIZE / (1024 * 1024)) * 10) / 10} МБ`;

/**
 * Минимум, который нужен логике отбора. Настоящий `File` подходит по форме,
 * но объявлять его здесь нельзя: модуль импортирует и сервер, где лежит
 * node-шный `File`, и тест, где файлы — обычные объекты.
 */
export interface AttachmentLike {
  name: string;
  size: number;
}

export interface PickResult<T extends AttachmentLike> {
  /** Новый набор: уже выбранное плюс принятое из этой пачки. */
  files: T[];
  /** Причины отказа за ЭТУ пачку, готовые к показу (см. doc-comment ниже). */
  rejected: string[];
}

/**
 * Добавляет пачку файлов к уже выбранным и объясняет каждый отказ.
 *
 * Отклонённый файл ОБЯЗАН оставить причину: молча исчезающий файл читается
 * посетителем как «прикрепилось» — заявка уходит без сметы, и это выясняется
 * уже в разговоре с менеджером. Причины копятся только за текущий вызов:
 * следующий выбор/drop начинает список заново.
 *
 * Дубль (совпали имя и размер) — единственный тихий пропуск: файл уже виден
 * в списке, сообщать не о чем.
 *
 * Функция чистая: не мутирует `current`, не трогает DOM — поэтому вся
 * арифметика лимитов покрывается юнит-тестами, а на долю компонента остаётся
 * только отрисовка.
 */
export function addAttachments<T extends AttachmentLike>(
  current: readonly T[],
  incoming: readonly T[],
): PickResult<T> {
  const files = [...current];
  const rejected: string[] = [];

  for (const file of incoming) {
    // Дедуп проверяется ПЕРВЫМ, до лимита числа: иначе повторный drop уже
    // приложенного файла при полном наборе выдавал бы «максимум 5 файлов» —
    // отказ, которого не было (файл на месте), про файл, который ничего не
    // занял. Посетитель принимался бы удалять что-то лишнее.
    if (files.some((picked) => picked.name === file.name && picked.size === file.size)) continue;
    if (files.length >= MAX_FILES) {
      rejected.push(`Файл «${file.name}» не добавлен: максимум ${MAX_FILES} файлов`);
      continue;
    }
    if (file.size > MAX_FILE_SIZE) {
      rejected.push(`Файл «${file.name}» не добавлен: больше ${MAX_FILE_SIZE_LABEL}`);
      continue;
    }
    // Пустышку сервер всё равно выбросит (`file.size === 0` в saveAttachments) —
    // лучше сказать об этом здесь, пока посетитель ещё может приложить нужный.
    if (file.size === 0) {
      rejected.push(`Файл «${file.name}» не добавлен: пустой файл`);
      continue;
    }
    files.push(file);
  }

  return { files, rejected };
}

/**
 * Расширение для подписи на иконке файла-не-картинки. Своё, а не серверный
 * `safeExt`: там фолбэк `.bin` уходит в имя файла на диске, здесь — слово
 * «файл» на плитке.
 */
export function attachmentExt(name: string): string {
  const match = (name || '').match(/\.([A-Za-z0-9]{1,8})$/);
  return match ? match[1].toLowerCase() : 'файл';
}
