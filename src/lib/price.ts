/**
 * Разбор цены из свободного формата фронтматтера (`productSchema.price`,
 * напр. «от 12 500 ₽») в число для structured data и товарных фидов.
 *
 * ЗАЧЕМ ОДИН ПАРСЕР НА ВСЕХ. Цена в контенте — строка: клиент пишет её так,
 * как говорит покупателю («от 12 500 ₽», «12 500 руб.»), и ни одна CMS не
 * заставит его вводить число. Потребителей у этой строки трое —
 * `ProductJsonLd.astro`, `yml.xml.ts`, `google-merchant.xml.ts`, — и если
 * каждый разберёт её по-своему, товар окажется «с ценой» в одном канале и
 * «без» в другом. Расхождение цены на сайте и в фиде Яндекс Директ считает
 * поводом отключить источник целиком, поэтому цифра обязана быть одна.
 *
 * РАЗРЯДЫ ПРОТИВ КОПЕЕК — единственное неочевидное место. И то и другое
 * отделяется точкой или запятой, и спутать их дорого: «99,90 ₽», разобранное
 * как разряды, даёт 9990 — цена в фиде в сто раз выше, чем на странице.
 * Различаем по длине хвостовой группы: разрядная группа всегда из ТРЁХ цифр
 * («12 500», «12.500», «12,500»), поэтому одна-две цифры после последнего
 * разделителя в конце числа — это дробная часть («99,90» → 99.9).
 *
 * Копейки при этом СОХРАНЯЕМ, а не отбрасываем и не округляем: цена в фиде
 * обязана совпадать с ценой на посадочной странице (расхождение — повод
 * отключить источник целиком), а дробную часть принимают все три потребителя —
 * YML `<price>`, `g:price` с двумя знаками и `lowPrice` в JSON-LD.
 *
 * Ничего не выдумывает: не распозналось — `undefined`, и потребитель просто
 * не эмитит оффер (см. doc-комментарии в feeds.ts и ProductJsonLd.astro).
 */
export function parsePrice(raw?: string): number | undefined {
  if (!raw) return undefined;
  // NBSP → обычный пробел (им разделяет разряды любой текстовый редактор),
  // затем первое число в строке.
  const match = raw.replace(/ /g, ' ').match(/\d[\d\s.,]*/);
  if (!match) return undefined;
  // Хвостовые разделители к числу не относятся: «12 500 руб.» → «12 500».
  const digits = match[0].replace(/[\s.,]+$/, '');
  const fraction = digits.match(/[.,](\d{1,2})$/);
  const intPart = (fraction ? digits.slice(0, digits.length - fraction[0].length) : digits)
    // Всё, что осталось между цифрами, — разделители разрядов.
    .replace(/[\s.,]/g, '');
  const value = Number.parseFloat(fraction ? `${intPart}.${fraction[1]}` : intPart);
  return Number.isFinite(value) && value > 0 ? value : undefined;
}
